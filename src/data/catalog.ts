/**
 * Ürün görselinden galeri türetir (aynı ürünün alternatif "çekimleri").
 * Gerçek fotoğraflar eklendiğinde ürüne doğrudan `gallery` yazmak yeterli.
 */
const galleryFor = (image: string): string[] => {
  const [, base, ext] = image.match(/^(.*)\.([a-z0-9]+)$/i) ?? []
  if (!base) return [image]
  return [image, `${base}-2.${ext}`, `${base}-3.${ext}`]
}

